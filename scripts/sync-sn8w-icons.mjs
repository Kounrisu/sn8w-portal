#!/usr/bin/env node
/**
 * Copies the icons the portal uses from the SN8W design system (PORTAL-24), read-only:
 * - icons SN8W already names (packages/icons/src/icons.ts), by their SN8W name;
 * - the others from the Aksel set kept in SN8W (packages/icons/sets/aksel, MIT, Nav), cleaned the
 *   way SN8W cleans them (scripts/use-aksel.mjs): only the shapes, their fixed colour removed, so
 *   they fill with the text colour.
 * Writes src/app/shared/icon/icons.generated.ts and licenses/aksel-icons.txt. Only drawings are
 * copied (MIT), never SN8W code. Nothing in SN8W is changed.
 *
 * Run: node scripts/sync-sn8w-icons.mjs   (SN8W_DIR overrides ../24-sn8w-design-system)
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sn8w = resolve(process.env.SN8W_DIR ?? join(root, '..', '24-sn8w-design-system'));
const iconsPkg = join(sn8w, 'packages', 'icons');

/** Portal name → where it comes from in SN8W: an SN8W icon, or an Aksel icon of its set. */
const USED = {
  moon: { sn8w: 'moon' },
  sun: { sn8w: 'sun' },
  'arrow-right': { sn8w: 'arrow-right' },
  'chevron-down': { sn8w: 'chevron-down' },
  'chevron-left': { sn8w: 'chevron-left' },
  'chevron-right': { sn8w: 'chevron-right' },
  accessibility: { sn8w: 'accessibility' },
  search: { sn8w: 'search' },
  x: { sn8w: 'x' },
  'user-check': { sn8w: 'user-check' },
  'user-minus': { sn8w: 'user-minus' },
  'chevron-up': { aksel: 'ChevronUp' },
  'external-link': { aksel: 'ExternalLink' },
  'drag-handle': { aksel: 'DragVertical' },
  expand: { aksel: 'Expand' },
  'arrow-left': { aksel: 'ArrowLeft' },
  code: { aksel: 'Code' },
  school: { aksel: 'HatSchool' },
  briefcase: { aksel: 'Briefcase' },
  verified: { aksel: 'SealCheckmark' },
  mail: { aksel: 'EnvelopeClosed' },
  wrench: { aksel: 'Wrench' },
  branching: { aksel: 'Branching' },
  ruler: { aksel: 'Ruler' },
  laptop: { aksel: 'Laptop' },
  lightning: { aksel: 'Lightning' },
  component: { aksel: 'Component' },
  'clipboard-check': { aksel: 'ClipboardCheckmark' },
  people: { aksel: 'PersonGroup' },
  pencil: { aksel: 'Pencil' },
};

for (const p of [join(iconsPkg, 'src', 'icons.ts'), join(iconsPkg, 'sets', 'aksel', 'icons.json')]) {
  if (!existsSync(p)) {
    console.error(`SN8W not found: ${p}. Set SN8W_DIR to the design system folder.`);
    process.exit(1);
  }
}

// SN8W's own icons: the inner markup in src/icons.ts ('name':\n '<path … />',).
const sn8wSource = readFileSync(join(iconsPkg, 'src', 'icons.ts'), 'utf8');
const block = sn8wSource.slice(sn8wSource.indexOf('export const icons'), sn8wSource.indexOf('export const iconSources'));
const sn8wIcons = {};
for (const m of block.matchAll(/'?([a-z0-9-]+)'?:\s*'([^']+)'/g)) sn8wIcons[m[1]] = m[2];

const set = JSON.parse(readFileSync(join(iconsPkg, 'sets', 'aksel', 'icons.json'), 'utf8'));
const byName = new Map(set.map((i) => [i.name, i]));

function akselShapes(name) {
  const file = byName.get(name)?.variants.stroke;
  if (!file) throw new Error(`Aksel has no Stroke icon named ${name}`);
  const svg = readFileSync(join(iconsPkg, 'sets', 'aksel', 'svg', file), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  const parts = inner.match(/<[a-z]+(?:\s+[a-z-]+="[^"]*")*\s*\/>/g) ?? [];
  if (!parts.length || parts.join('').replace(/\s/g, '') !== inner.replace(/\s/g, '')) {
    throw new Error(`${file} holds markup other than simple shapes`);
  }
  return parts.map((p) => p.replace(/\s+fill="#[0-9a-fA-F]{3,6}"/, '').replace(/\s*\/>$/, ' />')).join('');
}

const out = {};
const from = {};
for (const [name, src] of Object.entries(USED)) {
  if (src.sn8w) {
    if (!sn8wIcons[src.sn8w]) throw new Error(`SN8W has no icon named ${src.sn8w}`);
    out[name] = sn8wIcons[src.sn8w];
    from[name] = `SN8W ${src.sn8w}`;
  } else {
    out[name] = akselShapes(src.aksel);
    from[name] = `Aksel ${src.aksel} (SN8W set)`;
  }
  if (/[<>]\s*script|on[a-z]+=|javascript:/i.test(out[name])) throw new Error(`${name}: unexpected markup`);
}

let commit = 'unknown';
try {
  commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: sn8w, encoding: 'utf8' }).trim();
} catch {}
const aksel = JSON.parse(readFileSync(join(iconsPkg, 'sets', 'aksel', 'SOURCE.json'), 'utf8'));

const names = Object.keys(out);
const ts = `/**
 * Icons of the portal, from the SN8W design system (PORTAL-24). Generated by
 * scripts/sync-sn8w-icons.mjs from SN8W ${commit} — do not edit; run the script again.
 *
 * Every drawing is an Aksel Stroke icon (Nav, MIT licence: licenses/aksel-icons.txt, Aksel
 * ${aksel.version ?? ''}), 24×24, filled with the text colour. Only the inner shapes are stored.
 */

export const ICON_NAMES = [
${names.map((n) => `  '${n}',`).join('\n')}
] as const;

export type IconName = (typeof ICON_NAMES)[number];

export const ICONS: Record<IconName, string> = {
${names.map((n) => `  // ${from[n]}\n  '${n}': '${out[n]}',`).join('\n')}
};
`;
mkdirSync(join(root, 'src', 'app', 'shared', 'icon'), { recursive: true });
writeFileSync(join(root, 'src', 'app', 'shared', 'icon', 'icons.generated.ts'), ts);
mkdirSync(join(root, 'licenses'), { recursive: true });
writeFileSync(join(root, 'licenses', 'aksel-icons.txt'), readFileSync(join(iconsPkg, 'sets', 'aksel', 'LICENSE'), 'utf8'));
console.log(`${names.length} icons from SN8W ${commit}: ${names.filter((n) => USED[n].sn8w).length} SN8W icons, ${names.filter((n) => USED[n].aksel).length} from its Aksel set`);
